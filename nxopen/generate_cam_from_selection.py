def create_mill_operations(session, part, cam_session, selected, candidates):
    write_log('Attempting to create milling operations...')
    try:
        for feat in candidates:
            if feat['feature_type'] in ('pocket', 'profile', 'slot'):
                fid = feat['id']
                sel = next((s for s in selected if s['feature_id'] == fid), None)
                if not sel:
                    write_log(f'No selected tool for feature {fid}, skipping')
                    continue
                tool_id = sel['selected']
                write_log(f'Would create mill op for {fid} with tool {tool_id}')
        write_log('Mill operation creation (placeholder) complete.')
    except Exception:
        write_log('Exception while creating mill operations:')
        write_log(traceback.format_exc())


def run():
    write_log('NX CAM generation journal started')
    selected = load_json(SELECTED_PATH) or []
    candidates = load_json(CANDIDATES_PATH) or []
    toollib = load_json(TOOLLIB_PATH) or {}

    if not NX_AVAILABLE:
        write_log('NX not available: generating summary output only.')
        # Produce a small summary JSON pointing to chosen tools
        summary = {'selected_tools_summary': selected}
        outp = os.path.join(REPO_ROOT, 'output', 'nx_cam_summary.json')
        with open(outp, 'w', encoding='utf-8') as f:
            json.dump(summary, f, ensure_ascii=False, indent=2)
        write_log('Wrote summary to ' + outp)
        write_log('To generate full CAM operations, run this journal inside NX with CAM module available.')
        return

    try:
        session = NXOpen.Session.GetSession()
        work_part = session.Parts.Work
        display_part = session.Parts.Display
        write_log('NX session detected. Work part: ' + (work_part.Name if work_part else 'None'))
        # Attempt to get CAM session
        try:
            cam_session = NXOpen.CAM.CAMSession.GetSession(work_part)
        except Exception:
            cam_session = None
            write_log('CAMSession not available or failed to initialize')

        # Create drill ops
        create_drill_operations(session, work_part, cam_session, selected, candidates)
        # Create mill ops
        create_mill_operations(session, work_part, cam_session, selected, candidates)

        # Post-processing placeholder: user must run NX post builder to generate G-code
        write_log('CAM creation placeholder complete. Please open the part in NX CAM and run post-process to generate G-code (Fanuc Oi).')

    except Exception:
        write_log('Unexpected exception in journal:')
        write_log(traceback.format_exc())


if __name__ == '__main__':
    run()
