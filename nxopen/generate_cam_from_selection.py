import os
import json
import traceback

REPO_ROOT = os.path.join(os.path.dirname(__file__), '..')
SELECTED_PATH = os.path.join(REPO_ROOT, 'output', 'selected_tools.json')
CANDIDATES_PATH = os.path.join(REPO_ROOT, 'input', 'candidates.json')
TOOLLIB_PATH = os.path.join(REPO_ROOT, 'output', 'toollib_standard.json')
LOG_PATH = os.path.join(REPO_ROOT, 'output', 'nx_cam_journal_run.log')
GCODE_OUT = os.path.join(REPO_ROOT, 'output', 'generated_gcode.nc')


def write_log(s):
    with open(LOG_PATH, 'a', encoding='utf-8') as f:
        f.write(s + '\n')
    print(s)


try:
    import NXOpen
    import NXOpen.CAM
    NX_AVAILABLE = True
except Exception as e:
    NX_AVAILABLE = False
    write_log('NXOpen not available in this environment: ' + str(e))


